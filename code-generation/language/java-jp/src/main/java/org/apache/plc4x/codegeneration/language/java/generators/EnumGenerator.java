package org.apache.plc4x.codegeneration.language.java.generators;

import com.palantir.javapoet.*;
import org.apache.plc4x.plugins.codegenerator.language.mspec.model.definitions.DefaultEnumTypeDefinition;
import org.apache.plc4x.plugins.codegenerator.types.definitions.TypeDefinition;
import org.apache.plc4x.plugins.codegenerator.types.enums.EnumValue;
import org.apache.plc4x.plugins.codegenerator.types.references.SimpleTypeReference;
import org.apache.plc4x.plugins.codegenerator.types.references.TypeReference;
import org.apache.plc4x.java.spi.utils.StaticHelper;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;

import javax.lang.model.element.Modifier;
import java.io.File;
import java.io.IOException;
import java.util.ArrayList;
import java.util.List;
import java.util.Map;

public class EnumGenerator extends BaseGenerator<DefaultEnumTypeDefinition> {

    private static final Logger LOGGER = LoggerFactory.getLogger(EnumGenerator.class);

    public EnumGenerator(String targetPackage, File outputDirectory, File outputRootDir, Map<String, TypeDefinition> types, Map<String, String> externalTypes, Map<String, Object> options) {
        super(targetPackage, outputDirectory, outputRootDir, types, externalTypes, options);
    }

    @Override
    public void generate(DefaultEnumTypeDefinition enumTypeDefinition) {
        LOGGER.info("Generating: {}", enumTypeDefinition.getName());

        // Baseline: generate an empty enum as a starting point using JavaPoet.
        // Follow-up iterations can populate constants and fields mirroring the reference ModbusDataType.
        try {
            ClassName enumType = ClassName.get(targetPackage, enumTypeDefinition.getName());
            SimpleTypeReference simpleTypeReference = enumTypeDefinition.getType().orElseThrow();
            TypeName valueType = toTypeName(simpleTypeReference, true);
            TypeName nonSimpleValueType = toTypeName(simpleTypeReference, false);

            TypeSpec.Builder enumBuilder = TypeSpec.enumBuilder(enumTypeDefinition.getName())
                .addModifiers(Modifier.PUBLIC)
                .addJavadoc("Code generated by code-generation. DO NOT EDIT.\n");

            // Add all enum constants.
            for (EnumValue enumValue : enumTypeDefinition.getEnumValues()) {
                List<CodeBlock> args = new ArrayList<>();
                switch (simpleTypeReference.getBaseType()) {
                    case UINT:
                        if (simpleTypeReference.getSizeInBits() > 31) {
                            args.add(CodeBlock.of("($T) $LL", valueType, enumValue.getValue()));
                        } else {
                            args.add(CodeBlock.of("($T) $L", valueType, enumValue.getValue()));
                        }
                        break;
                    case INT:
                        if (simpleTypeReference.getSizeInBits() > 32) {
                            args.add(CodeBlock.of("($T) $LL", valueType, enumValue.getValue()));
                        } else {
                            args.add(CodeBlock.of("($T) $L", valueType, enumValue.getValue()));
                        }
                        break;
                    default:
                        args.add(CodeBlock.of("($T) $L", valueType, enumValue.getValue()));
                }

                // Output initializers for each constant.
                for (String constantName : enumTypeDefinition.getConstantNames()) {
                    TypeReference constantTypeReference = enumTypeDefinition.getConstantType(constantName);
                    TypeName constantType = toTypeName(constantTypeReference, true);
                    // If referencing an external non-simple type, override with its external FQN
                    if (constantTypeReference.isNonSimpleTypeReference() && (externalTypes != null) && externalTypes.containsKey(constantTypeReference.asNonSimpleTypeReference().orElseThrow().getName())) {
                        constantType = classNameFromFqn(externalTypes.get(constantTypeReference.asNonSimpleTypeReference().orElseThrow().getName()));
                    }
                    if (enumValue.getConstant(constantName).isPresent()) {
                        String constantValue = enumValue.getConstant(constantName).get();
                        if ("null".equalsIgnoreCase(constantValue)) {
                            args.add(CodeBlock.of("null"));
                        } else if (constantTypeReference.isSimpleTypeReference()) {
                            SimpleTypeReference simpleConstantTypeReference = constantTypeReference.asSimpleTypeReference().orElseThrow();
                            switch (simpleConstantTypeReference.getBaseType()) {
                                case UINT:
                                    // If it's a one-character string and is numeric, output it as char.
                                    if ((constantValue.length() == 1) && !isParsableAsNumber(constantValue)) {
                                        args.add(CodeBlock.of("($T) '$L'", constantType, constantValue));
                                    } else if (simpleConstantTypeReference.getSizeInBits() > 31) {
                                        args.add(CodeBlock.of("($T) $LL", constantType, constantValue));
                                    } else {
                                        args.add(CodeBlock.of("($T) $L", constantType, constantValue));
                                    }
                                    break;
                                case INT:
                                    // If it's a one-character string and is numeric, output it as char.
                                    if ((constantValue.length() == 1) && !isParsableAsNumber(constantValue)) {
                                        args.add(CodeBlock.of("($T) '$L'", constantType, constantValue));
                                    } else if (simpleConstantTypeReference.getSizeInBits() > 32) {
                                        args.add(CodeBlock.of("($T) $LL", constantType, constantValue));
                                    } else {
                                        args.add(CodeBlock.of("($T) $L", constantType, constantValue));
                                    }
                                    break;
                                case STRING:
                                case VSTRING:
                                    args.add(CodeBlock.of("$S", constantValue));
                                    break;
                                default:
                                    args.add(CodeBlock.of("($T) $L", constantType, constantValue));
                            }
                        } else if (constantTypeReference.isEnumTypeReference()) {
                            args.add(CodeBlock.of("$T.$L", constantType, constantValue));
                        } else {
                            args.add(CodeBlock.of("($T) $L", constantType, constantValue));
                        }
                    }
                }

                // Generate the constant entry.
                CodeBlock ctorArgs = CodeBlock.join(args, ", ");
                enumBuilder.addEnumConstant(enumValue.getName(), TypeSpec.anonymousClassBuilder("$L", ctorArgs).build());
            }

            // Add the static map of enum values which is used by the enumForValue method.
            ClassName mapClass = ClassName.get("java.util", "Map");
            ClassName hashMapClass = ClassName.get("java.util", "HashMap");
            ParameterizedTypeName mapOfValueEnum = ParameterizedTypeName.get(mapClass, nonSimpleValueType, enumType);
            enumBuilder.addField(FieldSpec.builder(mapOfValueEnum, "map", Modifier.PRIVATE, Modifier.STATIC, Modifier.FINAL).build());

            // Add the static initializer which populates the map.
            CodeBlock staticBlock = CodeBlock.builder()
                .addStatement("map = new $T<>()", hashMapClass)
                .beginControlFlow("for ($T value : $T.values())", enumType, enumType)
                .addStatement("map.put(value.getValue(), value)")
                .endControlFlow()
                .build();
            enumBuilder.addStaticBlock(staticBlock);

            // Add a field for the enum value.
            enumBuilder.addField(FieldSpec.builder(valueType, "value", Modifier.PRIVATE, Modifier.FINAL).build());

            // Add the constructor.
            MethodSpec.Builder constructorBuilder = MethodSpec.constructorBuilder()
                .addParameter(valueType, "value")
                .addStatement("this.value = value");

            // Add the value getter.
            enumBuilder.addMethod(MethodSpec.methodBuilder("getValue")
                .addModifiers(Modifier.PUBLIC)
                .returns(valueType)
                .addStatement("return value")
                .build());

            // Add fields and getter functions for constants.
            for (String constantName : enumTypeDefinition.getConstantNames()) {
                TypeReference constantTypeReference = enumTypeDefinition.getConstantType(constantName);
                TypeName constantType = toTypeName(constantTypeReference, true);

                // Generate the field.
                enumBuilder.addField(FieldSpec.builder(constantType, constantName, Modifier.PRIVATE, Modifier.FINAL).build());

                // Add a parameter to the constructor.
                constructorBuilder.addParameter(constantType, constantName)
                    .addStatement("this." + constantName + " = " + constantName);

                String constantNameCapitalized = StaticHelper.CAPITALIZE(constantName);
                // Generate the getter method.
                enumBuilder.addMethod(MethodSpec.methodBuilder("get" + constantNameCapitalized)
                    .addModifiers(Modifier.PUBLIC)
                    .returns(constantType)
                    .addStatement("return " + constantName)
                    .build());

                boolean isString = constantTypeReference.isStringTypeReference();
                enumBuilder.addMethod(MethodSpec.methodBuilder("firstEnumForField" + constantNameCapitalized)
                    .addParameter(ParameterSpec.builder(constantType, constantName).build())
                    .addModifiers(Modifier.PUBLIC, Modifier.STATIC)
                    .returns(enumType)
                    .addCode(CodeBlock.builder()
                        .beginControlFlow("for ($T _val : $T.values())", enumType, enumType)
                        .beginControlFlow(isString ? "if (_val.get$L().equals($L))" : "if (_val.get$L() == $L)", constantNameCapitalized, constantName)
                        .addStatement("return _val")
                        .endControlFlow()
                        .endControlFlow()
                        .addStatement("return null")
                        .build())
                    .build());

                enumBuilder.addMethod(MethodSpec.methodBuilder("enumsForField" + constantNameCapitalized)
                    .addParameter(ParameterSpec.builder(constantType, constantName).build())
                    .addModifiers(Modifier.PUBLIC, Modifier.STATIC)
                    .returns(ParameterizedTypeName.get(
                        ClassName.get(List.class),
                        enumType
                    ))
                    .addCode(CodeBlock.builder()
                        .addStatement("$T<$T> _values = new $T<>()", List.class, enumType, ArrayList.class)
                        .beginControlFlow("for ($T _val : $T.values())", enumType, enumType)
                        .beginControlFlow(isString ? "if (_val.get$L().equals($L))" : "if (_val.get$L() == $L)", constantNameCapitalized, constantName)
                        .addStatement("_values.add(_val)")
                        .endControlFlow()
                        .endControlFlow()
                        .addStatement("return _values")
                        .build())
                    .build());
            }

            // Create the constructor.
            MethodSpec constructor = constructorBuilder.build();
            enumBuilder.addMethod(constructor);

            // Add the enumForValue method for looking up an enum value by its value.
            enumBuilder.addMethod(MethodSpec.methodBuilder("enumForValue")
                .addModifiers(Modifier.PUBLIC, Modifier.STATIC)
                .returns(enumType)
                .addParameter(valueType, "value")
                .addStatement("return map.get(value)")
                .build());

            // Little helper method, to check if there is an enum defined for a given value.
            enumBuilder.addMethod(MethodSpec.methodBuilder("isDefined")
                .addModifiers(Modifier.PUBLIC, Modifier.STATIC)
                .returns(TypeName.BOOLEAN)
                .addParameter(valueType, "value")
                .addStatement("return map.containsKey(value)")
                .build());

            TypeSpec enumSpec = enumBuilder.build();

            JavaFile javaFile = JavaFile.builder(targetPackage, enumSpec)
                .addFileComment(APACHE_LICENSE_HEADER)
                .skipJavaLangImports(true)
                .build();

            // Write to the configured output root directory; JavaPoet will create package folders.
            javaFile.writeTo(outputRootDir);
        } catch (IOException e) {
            LOGGER.error("Error generating enum {}", enumTypeDefinition.getName(), e);
        }
    }

}
