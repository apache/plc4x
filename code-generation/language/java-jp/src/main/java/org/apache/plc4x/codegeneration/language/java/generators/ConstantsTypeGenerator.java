package org.apache.plc4x.codegeneration.language.java.generators;

import com.palantir.javapoet.FieldSpec;
import com.palantir.javapoet.JavaFile;
import com.palantir.javapoet.MethodSpec;
import com.palantir.javapoet.TypeSpec;
import org.apache.plc4x.java.spi.buffers.api.exceptions.BufferException;
import org.apache.plc4x.plugins.codegenerator.types.definitions.Argument;
import org.apache.plc4x.plugins.codegenerator.types.definitions.ConstantsTypeDefinition;
import org.apache.plc4x.plugins.codegenerator.types.definitions.TypeDefinition;
import org.apache.plc4x.plugins.codegenerator.types.fields.ConstField;
import org.apache.plc4x.java.spi.utils.StaticHelper;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;

import javax.lang.model.element.Modifier;
import java.io.File;
import java.io.IOException;
import java.util.Collections;
import java.util.List;
import java.util.Map;

public class ConstantsTypeGenerator extends BaseGenerator<ConstantsTypeDefinition> {

    private static final Logger LOGGER = LoggerFactory.getLogger(ConstantsTypeGenerator.class);

    public ConstantsTypeGenerator(String targetPackage, File outputDirectory, File outputRootDir, Map<String, TypeDefinition> types, Map<String, String> externalTypes, Map<String, Object> options) {
        super(targetPackage, outputDirectory, outputRootDir, types, externalTypes, options);
    }

    @Override
    public void generate(ConstantsTypeDefinition constantsTypeDefinition) throws BufferException {
        LOGGER.info("Generating: {}", constantsTypeDefinition.getName());
        List<Argument> parserArguments = constantsTypeDefinition.getAllParserArguments().orElse(Collections.emptyList());

        try {
            TypeSpec.Builder complexTypeBuilder = TypeSpec.classBuilder(constantsTypeDefinition.getName())
                .addModifiers(Modifier.PUBLIC)
                .addJavadoc("Code generated by code-generation. DO NOT EDIT.\n");

            // Generate some java constants for holing their values
            for (ConstField constField : constantsTypeDefinition.getConstFields()) {
                complexTypeBuilder.addField(FieldSpec.builder(toTypeName(constField.getType(), false), constField.getName().toUpperCase())
                    .addModifiers(Modifier.PUBLIC, Modifier.STATIC, Modifier.FINAL)
                    .initializer("$L", toParseExpression(constantsTypeDefinition, constField, constField.getType(), constField.getReferenceValue(), parserArguments))
                    .build());
            }

            // Generate the getter methods for const fields.
            for (ConstField constField : constantsTypeDefinition.getConstFields()) {
                complexTypeBuilder.addMethod(MethodSpec.methodBuilder("get" + StaticHelper.CAPITALIZE(constField.getName()))
                    .addModifiers(Modifier.PUBLIC)
                    .returns(toTypeName(constField.getType(), !constField.isOptionalField()))
                    .addStatement("return $L", constField.getName().toUpperCase())
                    .build());
            }

            TypeSpec dataIoSpec = complexTypeBuilder.build();

            JavaFile javaFile = JavaFile.builder(targetPackage, dataIoSpec)
                .addFileComment(APACHE_LICENSE_HEADER)
                .skipJavaLangImports(true)
                .build();

            // Write to the configured output root directory; JavaPoet will create package folders.
            javaFile.writeTo(outputRootDir);
        } catch (IOException e) {
            LOGGER.error("Error generating enum {}", constantsTypeDefinition.getName(), e);
        }
    }

}
